t "split args" $'just test \\\nlive'
t "<<- tabs" $'bash <<-\'EOF2\'\n\tju\\\n\tst test live\n\tEOF2'
t "<<-EOF two shells" $'bash <<-EOF2\n\tju\\\\\n\tst test\\\n\tlive\n\tEOF2'
